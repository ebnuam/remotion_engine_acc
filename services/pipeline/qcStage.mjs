/**
 * Pipeline Stage — QC (Unified Quality Gate before Publishing)
 *
 * Aggregates deterministic quality gates across:
 * 1. Editorial & Social Pack validation (`script_master.json`, `social_pack.json`)
 * 2. Audio loudness, duration, & commercial license gate (`audio/audio_summary.json`)
 * 3. Rendered MP4 technical verification (`ffprobe` 9:16 + audio track + duration)
 * 4. Optional frame-by-frame QA (`scripts/kokisoyo-qa/short_qa.py`)
 *
 * Persists `qc_report.json` in `jobDir` and blocks live `post` when `passed === false`.
 */

import { execFile } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { promisify } from "node:util";
import { atomicWriteFile } from "../tts-gateway/index.mjs";
import { AUDIO_LOUDNESS_STANDARDS, validateAudioMixMetrics } from "./audioStage.mjs";
import {
  EDITORIAL_RULES,
  validateEditorialPackage,
  validateSocialPack,
} from "./generateStage.mjs";
import { probeVideoFile } from "./renderStage.mjs";

const execFileAsync = promisify(execFile);

/**
 * Parses `qa_report.txt` generated by `scripts/kokisoyo-qa/short_qa.py`.
 */
export function parseShortQaReport(reportText) {
  const lines = String(reportText || "").split(/\r?\n/);
  const result = {
    specs: null,
    loudness: null,
    silences: null,
    blackFramesCount: null,
    whiteFramesCount: null,
    frozenSpansCount: null,
    popSpikesCount: null,
  };

  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith("SPECS ")) result.specs = line.slice(6).trim();
    else if (line.startsWith("LOUDNESS ")) result.loudness = line.slice(9).trim();
    else if (line.startsWith("SILENCES ")) result.silences = line.slice(9).trim();
    else if (/^BLACK/i.test(line)) {
      const m = line.match(/(\d+)/);
      if (m) result.blackFramesCount = Number(m[1]);
    } else if (/^WHITE/i.test(line)) {
      const m = line.match(/(\d+)/);
      if (m) result.whiteFramesCount = Number(m[1]);
    } else if (/^FROZEN/i.test(line)) {
      const m = line.match(/(\d+)/);
      if (m) result.frozenSpansCount = Number(m[1]);
    } else if (/^POPS/i.test(line)) {
      const m = line.match(/(\d+)/);
      if (m) result.popSpikesCount = Number(m[1]);
    }
  }

  return result;
}

export async function runQcStage({
  rootDir,
  jobDir,
  videoPath = undefined,
  requireCommercialAudio = false,
  strictAudioDuration = false,
  runShortQa = false,
  shortQaNoSheets = true,
  minDurationSec = EDITORIAL_RULES.minDurationSec,
  maxDurationSec = EDITORIAL_RULES.maxDurationSec,
  execFileImpl = execFileAsync,
} = {}) {
  fs.mkdirSync(jobDir, { recursive: true });

  const blockingErrors = [];
  const warnings = [];
  const checks = {
    editorial: { evaluated: false, passed: true, errors: [], warnings: [] },
    socialPack: { evaluated: false, passed: true, errors: [], warnings: [] },
    audio: { evaluated: false, passed: true, errors: [], warnings: [] },
    video: { evaluated: false, passed: true, errors: [], warnings: [] },
    shortQa: { evaluated: false, passed: true, qaDir: null, parsed: null },
  };

  // 1. Editorial check
  const scriptPath = path.join(jobDir, "script_master.json");
  if (fs.existsSync(scriptPath)) {
    const script = JSON.parse(fs.readFileSync(scriptPath, "utf8"));
    const ed = validateEditorialPackage(script);
    checks.editorial = {
      evaluated: true,
      passed: ed.passed,
      errors: ed.errors,
      warnings: ed.warnings,
      metrics: ed.metrics,
    };
    if (!ed.passed) {
      blockingErrors.push(...ed.errors.map((e) => `[editorial] ${e}`));
    }
    warnings.push(...ed.warnings.map((w) => `[editorial] ${w}`));
  }

  // 2. Social pack check
  const socialPath = path.join(jobDir, "social_pack.json");
  if (fs.existsSync(socialPath)) {
    const social = JSON.parse(fs.readFileSync(socialPath, "utf8"));
    const sp = validateSocialPack(social);
    checks.socialPack = {
      evaluated: true,
      passed: sp.passed,
      errors: sp.errors,
      warnings: [],
    };
    if (!sp.passed) {
      blockingErrors.push(...sp.errors.map((e) => `[social] ${e}`));
    }
  }

  // 3. Audio check (loudness, duration, commercial license policy)
  const audioSummaryPath = path.join(jobDir, "audio", "audio_summary.json");
  if (fs.existsSync(audioSummaryPath)) {
    const audioSummary = JSON.parse(fs.readFileSync(audioSummaryPath, "utf8"));
    const dur = audioSummary?.mix?.probe?.actualDurationSec;
    const mixCheck = validateAudioMixMetrics({
      durationSec: dur,
      wavLoudness: audioSummary?.mix?.loudness?.wav,
      aacLoudness: audioSummary?.mix?.loudness?.aac,
      minDurationSec,
      maxDurationSec,
      targetLufs: audioSummary?.mix?.targetLufs ?? AUDIO_LOUDNESS_STANDARDS.targetLufs,
    });

    const audioErrors = [...mixCheck.errors];
    const audioWarnings = [...mixCheck.warnings];

    if (strictAudioDuration && Number.isFinite(dur) && (dur < minDurationSec || dur > maxDurationSec)) {
      audioErrors.push(
        `Durasi audio ${dur.toFixed(2)}s di luar batas wajib ${minDurationSec}-${maxDurationSec}s.`
      );
    }

    const commercialAllowed = Boolean(audioSummary?.tts?.commercialPolicy?.allowed);
    const ttsMode = audioSummary?.tts?.mode || "draft";
    if (!commercialAllowed || ttsMode !== "final") {
      const licenseMsg = `Audio menggunakan TTS mode="${ttsMode}" (${audioSummary?.tts?.provider || "unknown"}) yang belum terverifikasi lisensi komersial final.`;
      if (requireCommercialAudio) {
        audioErrors.push(licenseMsg);
      } else {
        audioWarnings.push(licenseMsg);
      }
    }

    checks.audio = {
      evaluated: true,
      passed: audioErrors.length === 0,
      errors: audioErrors,
      warnings: audioWarnings,
      ttsMode,
      ttsProvider: audioSummary?.tts?.provider || null,
      commercialAllowed,
      durationSec: dur ?? null,
      loudness: audioSummary?.mix?.loudness ?? null,
    };

    if (audioErrors.length > 0) {
      blockingErrors.push(...audioErrors.map((e) => `[audio] ${e}`));
    }
    warnings.push(...audioWarnings.map((w) => `[audio] ${w}`));
  }

  // 4. Video check (`ffprobe` + optional `short_qa.py`)
  if (videoPath && fs.existsSync(videoPath)) {
    const probe = await probeVideoFile(videoPath, execFileImpl);
    const videoErrors = [];
    const videoWarnings = [];

    if (!probe.isVertical916) {
      videoErrors.push(
        `Resolusi video ${probe.width}x${probe.height} bukan format vertikal 9:16 (height harus > width).`
      );
    }
    if (!probe.hasAudio) {
      videoErrors.push("Video MP4 tidak memiliki audio track.");
    }
    if (!Number.isFinite(probe.durationSec) || probe.durationSec <= 0) {
      videoErrors.push("Durasi video MP4 tidak valid.");
    } else if (probe.durationSec < minDurationSec || probe.durationSec > maxDurationSec) {
      videoWarnings.push(
        `Durasi video MP4 ${probe.durationSec.toFixed(2)}s di luar target editorial ${minDurationSec}-${maxDurationSec}s.`
      );
    }

    checks.video = {
      evaluated: true,
      passed: videoErrors.length === 0,
      errors: videoErrors,
      warnings: videoWarnings,
      videoPath,
      probe,
    };
    if (videoErrors.length > 0) {
      blockingErrors.push(...videoErrors.map((e) => `[video] ${e}`));
    }
    warnings.push(...videoWarnings.map((w) => `[video] ${w}`));

    if (runShortQa) {
      const qaDir = path.join(jobDir, "qa_render");
      const qaScript = path.join(rootDir, "scripts", "kokisoyo-qa", "short_qa.py");
      const qaArgs = [qaScript, videoPath, qaDir];
      if (shortQaNoSheets) qaArgs.push("--no-sheets");
      await execFileImpl("python3", qaArgs, {
        cwd: rootDir,
        timeout: 120_000,
        maxBuffer: 8 * 1024 * 1024,
      });

      const reportMdPath = path.join(qaDir, "report.md");
      const reportTxtPath = path.join(qaDir, "qa_report.txt");
      const actualReportPath = fs.existsSync(reportMdPath)
        ? reportMdPath
        : fs.existsSync(reportTxtPath)
          ? reportTxtPath
          : null;
      const parsed = actualReportPath
        ? parseShortQaReport(fs.readFileSync(actualReportPath, "utf8"))
        : null;
      checks.shortQa = {
        evaluated: true,
        passed: true,
        qaDir,
        reportTxtPath: actualReportPath,
        parsed,
      };
    }
  }

  const report = {
    passed: blockingErrors.length === 0,
    blockingErrors,
    warnings,
    checks,
    evaluatedAt: new Date().toISOString(),
  };

  const reportPath = path.join(jobDir, "qc_report.json");
  atomicWriteFile(reportPath, JSON.stringify(report, null, 2));

  return {
    ok: report.passed,
    reportPath,
    ...report,
  };
}
